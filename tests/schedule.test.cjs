const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
const start = html.indexOf('      function _mergeScheduleSources(');
const end = html.indexOf('      function _syncScheduleSourceUi(', start);
const context = {};
vm.createContext(context);
vm.runInContext(html.slice(start, end), context);
const merge = items => JSON.parse(JSON.stringify(context._mergeScheduleSources(items)));
const event = {date:'2026-10-27',time:'18:00',title:'공통 일정',source:'mnetplus'};
const matches = merge([event,{...event,title:'<공통 일정>',source:'blip',link:'https://s.blip.kr/s/test'}]);
assert.equal(matches.length,1);
assert.deepEqual(matches[0].sources,['mnetplus','blip']);
assert.equal(matches[0].link,'https://s.blip.kr/s/test');
assert.equal(merge([event,{...event,source:'blip',time:'19:00'}]).length,2);
assert.equal(merge([event,{...event,source:'blip',title:'다른 일정'}]).length,2);
assert.equal(merge([{...event,source:'manual'}])[0].sources.length,0);
assert.equal(event.sources,undefined);
assert(html.includes('data-action="setScheduleSource"'));
assert(html.includes('const upcoming = _allScheduleData.filter'));
console.log('PASS: schedule duplicate boundaries, source provenance and immutable inputs');
