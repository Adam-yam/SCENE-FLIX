const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const context = {window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'assets/search/search-v1.min.js'),'utf8'),context);
const rank = (items,q,ordered=true) => Array.from(context.window.SceneSearch.rank(items,q,x=>x.title,ordered));
const a={title:'RESCENE 리센느 Love Attack 음악중심'}, b={title:'리센느 러브 어택 비하인드'}, c={title:'Pretty Girl 미나미'}, d={title:'다른 아티스트 인터뷰'};
const items=[d,c,b,a];
assert.deepEqual(rank(items,'ㄹㅅㄴ'),[b,a]);
assert.deepEqual(rank(items,'ㅁㄴㅁ'),[c]);
assert.deepEqual(rank(items,'loveattack'),[a]);
assert.deepEqual(rank(items,'ATTACK RESCENE'),[a]);
assert.deepEqual(rank(items,'ㄹㅅㄴ 비하인드'),[b]);
assert.deepEqual(rank(items,'Love Attak'),[a]);
assert.deepEqual(rank(items,'리센느'.normalize('NFD')),[b,a]);
assert.deepEqual(rank(items,'존재하지않는검색어'),[]);
assert.deepEqual(rank(items,''),items);
assert.deepEqual(rank(items,'ㄹㅅㄸ'),[]);
assert.deepEqual(rank([{title:'2026.10.27'}],'2026.10.28'),[]);
assert.deepEqual(rank([{title:'미나미'}],'메이'),[]);
assert.deepEqual(rank([a],'<img src=x onerror=alert(1)>'),[]);
const exact={title:'Pretty Girl'},typo={title:'Prety Girl'};
assert.deepEqual(rank([typo,exact],'Pretty Girl'),[exact,typo]);
assert.deepEqual(rank([typo,exact],'Pretty Girl',false),[typo,exact]);
const updated={title:'old title'};
assert.equal(rank([updated],'ㅁㄴㅁ').length,0);
updated.title='미나미';
assert.deepEqual(rank([updated],'ㅁㄴㅁ'),[updated]);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.indexOf('src="assets/search/search-v1.min.js"')<html.indexOf('<script data-scene-events='));
assert(html.includes('state.items.filter(item => _searchItemText(item).date.includes(state.dateQuery))'));
assert(!html.includes('data.text.includes(state.q)'));
console.log('PASS: initials, spacing, token order, mixed initials, typo tolerance, Unicode, negative queries, exact-first ranking, stable ordering, metadata invalidation and date isolation');
